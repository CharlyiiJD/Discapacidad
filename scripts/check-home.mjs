import { chromium, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

await mkdir('artifacts', { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const failures = []
try {
  for (const width of [1440, 2560, 390, 320]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: 'reduce' })
    const page = await context.newPage()
    page.on('pageerror', (error) => failures.push(error.message))
    await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
    await page.locator('.hero-image').first().waitFor()
    await page.evaluate(() => document.fonts.ready)
    await page.locator('img').evaluateAll((images) => images.forEach((image) => { image.loading = 'eager' }))
    for (const image of await page.locator('img').all()) await image.evaluate((img) => img.decode().catch(() => undefined))
    await page.evaluate(() => window.scrollTo(0, 0))
    const geometry = await page.evaluate(() => {
      const hero = document.querySelector('.university-hero').getBoundingClientRect()
      const header = document.querySelector('.academic-header').getBoundingClientRect()
      const cards = document.querySelector('.quick-access').getBoundingClientRect()
      const main = document.querySelector('.content-container').getBoundingClientRect()
      const images = [...document.querySelectorAll('img')].map((img) => ({ src: img.src, loaded: img.complete && img.naturalWidth > 0 }))
      return { hero: { width: hero.width, height: hero.height, top: hero.top, bottom: hero.bottom }, header: { width: header.width, bottom: header.bottom }, cards: { width: cards.width, top: cards.top }, container: main.width, overflow: document.documentElement.scrollWidth > innerWidth, images }
    })
    assert.equal(geometry.hero.height, 500)
    assert.equal(geometry.hero.width, width)
    assert.equal(geometry.hero.top, geometry.header.bottom)
    assert.equal(geometry.header.width, width)
    assert.equal(geometry.overflow, false, `Horizontal overflow at ${width}`)
    assert.deepEqual(geometry.images.filter((image) => !image.loaded), [], 'Images must load')
    if (width >= 1440) {
      assert.equal(geometry.cards.width, 1200)
      assert.equal(geometry.hero.bottom - geometry.cards.top, 100)
    }
    if (width === 2560) assert.equal(geometry.container, 1400)
    await page.screenshot({ path: `artifacts/home-${width}.png`, fullPage: true })
    await page.keyboard.press('Tab')
    assert.equal(await page.locator('.skip-link').evaluate((node) => node === document.activeElement), true)
    await page.keyboard.press('Enter')
    assert.equal(await page.locator('main').evaluate((node) => node === document.activeElement), true)
    for (let slide = 0; slide < 3; slide++) {
      const active = page.locator('.university-hero .swiper-slide-active')
      assert.equal(await active.locator('h2').innerText(), ['My-University', 'Educaci\u00f3n para todos', 'Conocimiento que transforma'][slide])
      const copy = await active.locator('.hero-copy').boundingBox()
      const controls = await page.locator('.hero-controls').boundingBox()
      if (width <= 760) assert.ok(copy.y + copy.height <= controls.y, `Hero text overlaps controls on slide ${slide + 1} at ${width}`)
      assert.equal(await page.locator('.university-hero .swiper-slide:not(.swiper-slide-active) article:not([inert])').count(), 0)
      await page.getByRole('button', { name: 'Bot\u00f3n para mostrar la imagen siguiente' }).click()
    }
    const pause = page.getByRole('checkbox', { name: /Pausar carrusel/ })
    await pause.uncheck()
    await pause.check()
    assert.equal(await pause.isChecked(), true)
    assert.equal(await page.locator('.news-item').count(), 6)
    if (width >= 1440) {
      const columns = await page.locator('.news-events-grid > section').evaluateAll((nodes) => nodes.map((node) => node.getBoundingClientRect().width))
      assert.equal(columns[0], columns[1])
      const cardHeights = await page.locator('.shortcut').evaluateAll((nodes) => nodes.map((node) => node.getBoundingClientRect().height))
      assert.ok(cardHeights.every((height) => height <= 260), 'Quick access cards should remain compact')
    }
    assert.equal(await page.locator('.program-carousel .swiper-slide').count(), 10)
    await page.locator('.program-carousel .swiper-pagination button').last().click()
    assert.equal(await page.locator('.program-carousel .swiper-slide').last().locator('article').getAttribute('inert'), null)
    await page.locator('.program-carousel .swiper-pagination button').first().click()
    for (const id of ['contact-name', 'contact-email', 'contact-topic', 'contact-message']) {
      const helpId = await page.locator(`#${id}`).getAttribute('aria-describedby')
      assert.ok(helpId)
      assert.ok((await page.locator(`#${helpId}`).innerText()).length > 30)
      assert.equal(await page.locator(`#${helpId}`).evaluate((node) => getComputedStyle(node).clipPath), 'inset(50%)')
    }
    const newsColumns = await page.locator('.news-list').evaluate((node) => getComputedStyle(node).gridTemplateColumns.split(' ').length)
    assert.equal(newsColumns, width >= 480 ? 2 : 1)
    assert.equal(await page.getByRole('form', { name: 'Formulario de contacto' }).isVisible(), true)
    await expect(page.getByRole('textbox', { name: 'Nombre completo', exact: true })).toHaveAccessibleDescription(/Ingresa tu nombre y apellidos/)
    await expect(page.getByRole('combobox', { name: /Sobre qué quieres conversar/ })).toHaveAccessibleDescription(/recorre las opciones con las flechas/)
    assert.equal(await page.getByText('Pausar carreras', { exact: true }).count(), 0)
    assert.equal(await page.locator('img:not([aria-hidden="true"]):not([alt]), .news-item img[alt=""]').count(), 0)
    await page.getByRole('button', { name: `Leer noticia: Un campus que se construye para todas las personas` }).click()
    assert.equal(await page.getByRole('dialog').isVisible(), true)
    await page.keyboard.press('Escape')
    assert.equal(await page.getByRole('dialog').isVisible(), false)
    await page.getByLabel('Nombre completo').fill('Persona de prueba')
    await page.getByLabel('Correo electr\u00f3nico').fill('prueba@example.com')
    await page.getByLabel('\u00bfSobre qu\u00e9 quieres conversar?').selectOption({ label: 'Accesibilidad y apoyo' })
    await page.getByLabel('Tu mensaje', { exact: true }).fill('Consulta de prueba de accesibilidad.')
    await page.getByRole('button', { name: /Guardar consulta/ }).click()
    assert.ok(await page.getByRole('status').innerText())
    assert.ok(await page.evaluate(() => localStorage.getItem('university-contact-draft')))
    await page.evaluate(() => localStorage.removeItem('university-contact-draft'))
    const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    failures.push(...audit.violations.map((v) => `${width}: ${v.id}: ${v.nodes.map((n) => n.target.join(' ')).join(', ')}`))
    console.log(JSON.stringify({ width, overflow: geometry.overflow, newsColumns, accessibilityViolations: audit.violations.length }))
    await context.close()
  }
  const manualContext = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' })
  const manualPage = await manualContext.newPage()
  await manualPage.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
  const programs = manualPage.locator('.program-carousel')
  const initialIndex = await programs.evaluate((node) => node.swiper.activeIndex)
  await programs.hover()
  await manualPage.waitForTimeout(8000)
  assert.equal(await programs.evaluate((node) => node.swiper.activeIndex), initialIndex)
  await manualPage.getByRole('button', { name: 'Mostrar las carreras siguientes' }).click()
  await expect.poll(() => programs.evaluate((node) => node.swiper.activeIndex)).not.toBe(initialIndex)
  await manualPage.getByRole('button', { name: 'Mostrar las carreras anteriores' }).click()
  await expect.poll(() => programs.evaluate((node) => node.swiper.activeIndex)).toBe(initialIndex)
  await manualContext.close()
  assert.deepEqual(failures, [], 'Browser or accessibility failures')
} finally {
  await browser.close()
}
